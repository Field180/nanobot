    def run_tests(self):
        """运行所有测试"""
        test_cases = self.generate_test_cases()
        
        print(f"开始测试智能任务描述生成器...")
        print(f"测试用例总数: {len(test_cases)}")
        print("=" * 80)
        
        results = {
            'passed': 0,
            'failed': 0,
            'categories': {}
        }
        
        for i, test_case in enumerate(test_cases, 1):
            task = {
                'id': test_case['id'],
                'name': test_case['name'],
                'command': test_case['command'],
                'description': ''  # 初始为空，等待生成
            }
            
            # 生成描述
            generated_desc = self.generate_task_description(task)
            
            # 验证生成的描述
            is_valid = self.validate_description(generated_desc, test_case)
            
            if is_valid:
                results['passed'] += 1
                status = "✅ 通过"
            else:
                results['failed'] += 1
                status = "❌ 失败"
            
            # 分类统计
            category = test_case.get('expected_category', 'unknown')
            if category not in results['categories']:
                results['categories'][category] = {'passed': 0, 'failed': 0, 'total': 0}
            results['categories'][category]['total'] += 1
            if is_valid:
                results['categories'][category]['passed'] += 1
            else:
                results['categories'][category]['failed'] += 1
            
            # 输出进度（每100个显示一次）
            if i % 100 == 0:
                print(f"已测试: {i}/{len(test_cases)} - 当前通过率: {results['passed']/i*100:.1f}%")
        
        # 生成报告
        self.generate_report(results, test_cases)
        
        return results
    
    def validate_description(self, desc, test_case):
        """验证生成的描述是否有效"""
        if not desc or len(desc) < 5:
            return False
        
        # 检查是否包含中文（至少要有一些中文字符）
        chinese_chars = len([c for c in desc if '\u4e00' <= c <= '\u9fff'])
        if chinese_chars < 3:
            return False
        
        # 检查是否是通用描述（不够好）
        if desc == '执行预定维护任务' or desc.startswith('python') or desc.startswith('./'):
            return False
        
        return True
    
